ONSETS = {ident: value for ident, value, _ in ROWS}


def doc_of(ident: str) -> str:
    return ident.rsplit(".", 1)[0]


def documents() -> list[str]:
    """Return each document that holds a row, in the order of the table."""
    return list(dict.fromkeys(doc_of(ident) for ident, _, _ in ROWS))


def _put(path: Path, value: object) -> None:
    """Write the field onset after the field mode, or after waivable where a profile has no mode."""
    text = path.read_text(encoding="utf-8")
    line = f"onset: {json.dumps(value)}"
    if re.search(r"^onset: .*$", text, flags=re.M):
        text = re.sub(r"^onset: .*$", lambda _m: line, text, count=1, flags=re.M)
    else:
        anchor = "mode" if re.search(r"^mode: ", text, flags=re.M) else "waivable"
        text, n = re.subn(rf"^({anchor}: .*)$", lambda m: f"{m.group(1)}\n{line}", text, count=1, flags=re.M)
        if n != 1:
            raise ValueError(f"{path}: no field {anchor}")
    path.write_text(text, encoding="utf-8")


def apply_fields(root: Path, doc_id: str) -> int:
    """Set the field onset on each provision of one document; refuse a waivable provision without a row."""
    root = Path(root)
    folder = root / doc_id.replace(".", "/")
    count = 0
    for path in sorted(folder.glob("[0-9]*.md"), key=lambda p: int(p.stem)):
        meta, _ = parse_entry(path.read_text(encoding="utf-8"))
        ident = meta["id"]
        if ident not in ONSETS:
            if meta.get("waivable"):
                raise ValueError(f"{ident}: waivable and without a row of the onset table")
            continue
        if not meta.get("waivable"):
            raise ValueError(f"{ident}: binds at every class and has a row of the onset table")
        if ONSETS[ident] is not None:
            _put(path, ONSETS[ident])
            count += 1
    return count
